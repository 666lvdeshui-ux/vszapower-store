/**
 * Main dynamic content translation function.
 * Translates dynamic string into target language using exact dictionary matches + phrase keyword replacements.
 */
export function translateDynamicContent(text: string | undefined | null, lang: string): string {
  if (!text) return '';
  if (lang === 'zh-CN') return text;

  const trimmed = text.trim();

  // 1. Check exact dictionary match
  if (DYNAMIC_DICTIONARY[trimmed] && DYNAMIC_DICTIONARY[trimmed][lang]) {
    return DYNAMIC_DICTIONARY[trimmed][lang];
  }

  // 2. Perform phrase keyword replacement for non-exact strings
  let result = text;
  const replacements = KEYWORD_REPLACEMENTS[lang] || KEYWORD_REPLACEMENTS['en'];
  if (replacements) {
    Object.keys(replacements).forEach((key) => {
      if (result.includes(key)) {
        result = result.replaceAll(key, replacements[key]);
      }
    });
  }

  return result;
}
