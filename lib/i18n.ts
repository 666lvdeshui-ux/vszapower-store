export function detectBrowserLanguage(): string {
  if (typeof window === 'undefined' || !navigator) return 'en';

  const browserLang = (navigator.language || (navigator.languages && navigator.languages[0]) || 'zh-CN').toLowerCase();

  if (browserLang.startsWith('de')) return 'de';
  if (browserLang.startsWith('ja')) return 'ja';
  if (browserLang.startsWith('es')) return 'es';
  if (browserLang.startsWith('ko')) return 'ko';
  if (browserLang.startsWith('he') || browserLang.startsWith('iw')) return 'he';
  if (browserLang.startsWith('ar')) return 'ar';
  if (browserLang.startsWith('fr')) return 'fr';
  if (browserLang.startsWith('pt')) return 'pt';
  if (browserLang.startsWith('ru')) return 'ru';
  if (browserLang.startsWith('vi')) return 'vi';
  if (browserLang === 'zh-hk' || browserLang === 'zh-mo') return 'zh-HK';
  if (browserLang === 'zh-tw') return 'zh-TW';
  if (browserLang.startsWith('zh')) return 'zh-CN';
  if (browserLang.startsWith('en')) return 'en';

  return 'en';
}

